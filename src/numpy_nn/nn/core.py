"""
Базовые абстракции для нейросетевых модулей.

Содержит два фундаментальных класса:

- ``Parameter`` — обёртка над обучаемым массивом (значения + градиенты);
- ``Module`` — базовый интерфейс для слоёв, активаций, контейнеров и лоссов.

Все остальные модули библиотеки наследуются от ``Module`` и работают
с ``Parameter``. Такой дизайн повторяет структуру PyTorch и позволяет
оптимизаторам работать единообразно со всеми моделями.
"""
from __future__ import annotations

import numpy as np
from numpy.typing import NDArray


class Parameter:
    """
    Обучаемый параметр: массив значений и соответствующий градиент.

    Контейнер ничего не знает о слоях, моделях или оптимизаторах.
    Его задача — хранить ``data`` и ``grad`` и предоставлять простейшие
    операции над ними.

    Attributes:
        data: Массив значений формы ``(..., )`` и dtype ``np.float64``.
            Всегда копия переданного массива — внешние изменения
            не влияют на параметр.
        grad: Массив градиента той же формы, что ``data``, либо ``None``,
            если backward ещё не вызывался. Выставляется в ``None``
            методом :meth:`zero_grad`.

    Example:
        >>> p = Parameter(np.array([1.0, 2.0, 3.0]))
        >>> p.shape
        (3,)
        >>> p.grad is None
        True
    """
    def __init__(self, data: NDArray[np.float64]) -> None:
        """
        Создаёт параметр из массива, копируя данные.

        Args:
            data: Исходный массив произвольной формы. Копируется
                и приводится к ``np.float64``.
        """
        self.data: NDArray[np.float64] = np.array(data, dtype=np.float64, copy=True)
        self.grad: NDArray[np.float64] | None = None

    def zero_grad(self) -> None:
        """
        Обнуляет градиент, выставляя ``grad = None``.

        Используется перед каждой итерацией обучения, чтобы градиенты
        предыдущего шага не накапливались. ``None`` вместо нулевого
        массива экономит память: оптимизатор пропускает параметры
        без градиента.
        """
        self.grad = None

    @property
    def shape(self) -> tuple[int, ...]:
        """
        Форма массива значений.

        Property, а не поле: форма всегда производна от ``data``,
        поэтому её не нужно обновлять вручную после изменений.

        Returns:
            Кортеж размерностей, например ``(3, 4)`` для матрицы 3×4.
        """
        return self.data.shape


class Module:
    """
    Базовый класс для всех нейросетевых модулей.

    Задаёт единый интерфейс: ``forward``, ``backward``, ``parameters``,
    ``zero_grad``. Наследники реализуют ``forward`` и ``backward``
    и, если у них есть обучаемые параметры, переопределяют
    ``parameters``.

    Модуль сам по себе не хранит данных. Он нужен только как контракт
    для наследников: ``Linear``, ``ReLU``, ``Sequential``,
    ``CrossEntropyLoss`` и так далее.

    Example:
        >>> class MyModule(Module):
        ...     def forward(self, x):
        ...         return x * 2
        ...     def backward(self, dout):
        ...         return dout * 2
        >>> m = MyModule()
        >>> m(np.array([1.0, 2.0]))
        array([2., 4.])
    """
    def __init__(self) -> None:
        """
        Инициализирует модуль.

        Пустой. Наследники сами создают нужные поля. Определён явно,
        чтобы подчеркнуть отсутствие магии.
        """

    def __call__(self, x: NDArray[np.float64]) -> NDArray[np.float64]:
        """
        Вызывает :meth:`forward`.

        Позволяет писать ``layer(x)`` вместо ``layer.forward(x)`` —
        синтаксис, привычный по PyTorch.

        Args:
            x: Входной массив.

        Returns:
            Результат прямого прохода.
        """
        return self.forward(x)

    def forward(self, x: NDArray[np.float64]) -> NDArray[np.float64]:
        """
        Прямой проход модуля.

        Абстрактный метод. Должен быть реализован в наследнике.

        Args:
            x: Входной массив формы, специфичной для конкретного слоя.

        Returns:
            Выходной массив.

        Raises:
            NotImplementedError: Если наследник не реализовал метод.
        """
        raise NotImplementedError(
            'forward должен быть реализован в наследнике, иначе ничего не работает'
        )

    def backward(self, dout: NDArray[np.float64]) -> NDArray[np.float64]:
        """
        Обратный проход модуля.

        Принимает градиент по выходу и возвращает градиент по входу.
        Если у модуля есть параметры, дополнительно записывает
        градиенты в ``Parameter.grad``.

        Абстрактный метод. Должен быть реализован в наследнике.

        Args:
            dout: Градиент функции потерь по выходу модуля.

        Returns:
            Градиент функции потерь по входу модуля — для передачи
            предыдущему слою.

        Raises:
            NotImplementedError: Если наследник не реализовал метод.
        """        
        raise NotImplementedError(
            'backward должен быть реализован в наследнике, иначе ничего не работает'
        )

    def parameters(self) -> list[Parameter]:
        """
        Список обучаемых параметров модуля.

        По умолчанию пустой — для модулей без параметров (активации,
        лоссы). Наследники с параметрами переопределяют метод.
        Контейнеры (например, ``Sequential``) собирают параметры
        всех вложенных модулей.

        Returns:
            Список :class:`Parameter`.
        """
        return []

    def zero_grad(self) -> None:
        """
        Обнуляет градиенты всех параметров модуля.

        Рекурсивно обходит :meth:`parameters` и вызывает
        :meth:`Parameter.zero_grad` у каждого.
        """
        for p in self.parameters():
            p.zero_grad()
